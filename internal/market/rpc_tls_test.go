func TestMoneroRPCPrivateCA(t *testing.T) {
	for _, name := range []string{"MONERO_RPC_CA", "MONERO_RPC_CERT", "MONERO_RPC_KEY"} {
		t.Setenv(name, "")
	}
	srv := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		w.Write([]byte(`{"jsonrpc":"2.0","id":"opsecmkt","result":{"ready":true}}`))
	}))
	defer srv.Close()
	ca := filepath.Join(t.TempDir(), "ca.pem")
	if err := os.WriteFile(ca, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: srv.Certificate().Raw}), 0600); err != nil {
		t.Fatal(err)
	}
	client, err := newRPCClient("monero wallet", srv.URL, "2.0", true)
	if err != nil {
		t.Fatal(err)
	}
	var result map[string]bool
	if err := client.call(context.Background(), "", "get_info", nil, &result); err == nil {
		t.Fatal("trusted unknown CA")
	}
	t.Setenv("MONERO_RPC_CA", ca)
	client, err = newRPCClient("monero wallet", srv.URL, "2.0", true)
	if err != nil {
		t.Fatal(err)
	}
	if err := client.call(context.Background(), "", "get_info", nil, &result); err != nil || !result["ready"] {
		t.Fatalf("private CA: %v %v", err, result)
	}
	if _, err := newRPCClient("monero wallet", strings.Replace(srv.URL, "https:", "http:", 1), "2.0", true); err == nil {
		t.Fatal("silently ignored TLS for HTTP")
	}
	t.Setenv("MONERO_RPC_CERT", ca)
	if _, err := newRPCClient("monero wallet", srv.URL, "2.0", true); err == nil {
		t.Fatal("accepted incomplete client identity")
	}
	t.Setenv("MONERO_RPC_CERT", "")
	t.Setenv("MONERO_RPC_CA", filepath.Join(t.TempDir(), "missing"))
	if _, err := newRPCClient("monero wallet", srv.URL, "2.0", true); err == nil {
		t.Fatal("silently ignored missing CA")
	}
}

// testPKI is a throwaway certificate authority generated by the test; its keys exist only in the test's
// temporary directory.
type testPKI struct {
	cert *x509.Certificate
	key  *ecdsa.PrivateKey
	dir  string
}

func newTestPKI(t *testing.T, name string) *testPKI {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	tmpl := &x509.Certificate{
		SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: name},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour),
		IsCA: true, BasicConstraintsValid: true, KeyUsage: x509.KeyUsageCertSign,
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatal(err)
	}
	return &testPKI{cert: cert, key: key, dir: t.TempDir()}
}

// caFile writes the CA certificate as a PEM file, as an operator copies the public issuing CA.
func (p *testPKI) caFile(t *testing.T) string {
	t.Helper()
	path := filepath.Join(p.dir, "ca.pem")
	if err := os.WriteFile(path, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: p.cert.Raw}), 0600); err != nil {
		t.Fatal(err)
	}
	return path
}

func (p *testPKI) pool() *x509.CertPool {
	pool := x509.NewCertPool()
	pool.AddCert(p.cert)
	return pool
}

// leaf issues a certificate with the given extended key usage (and IP names) and writes it with its key (mode 0600)
// under the CA's directory, returning the TLS pair and both file paths.
func (p *testPKI) leaf(t *testing.T, name string, usage x509.ExtKeyUsage, ips ...net.IP) (tls.Certificate, string, string) {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	serial, err := rand.Int(rand.Reader, big.NewInt(1<<62))
	if err != nil {
		t.Fatal(err)
	}
	tmpl := &x509.Certificate{
		SerialNumber: serial, Subject: pkix.Name{CommonName: name},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour),
		KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{usage}, IPAddresses: ips,
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, p.cert, &key.PublicKey, p.key)
	if err != nil {
		t.Fatal(err)
	}
	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		t.Fatal(err)
	}
	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER})
	certPath, keyPath := filepath.Join(p.dir, name+".pem"), filepath.Join(p.dir, name+".key")
	if err := os.WriteFile(certPath, certPEM, 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(keyPath, keyPEM, 0600); err != nil {
		t.Fatal(err)
	}
	pair, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		t.Fatal(err)
	}
	return pair, certPath, keyPath
}

// setMoneroRPCTLSEnv sets the three transport variables newRPCClient reads (empty clears one).
func setMoneroRPCTLSEnv(t *testing.T, ca, cert, key string) {
	t.Helper()
	t.Setenv("MONERO_RPC_CA", ca)
	t.Setenv("MONERO_RPC_CERT", cert)
	t.Setenv("MONERO_RPC_KEY", key)
}

// payRPCTLS is the Digest JSON-RPC test server (payRPCServer) served over TLS, counting the TLS connections it
// accepts and recording the client certificate's common name.
type payRPCTLS struct {
	*payRPCServer
	conns atomic.Int32
	peer  atomic.Value // string
}

// startPayRPCTLS serves over TLS with serverCert; with clientCAs set, the server requires and verifies a client
// certificate from them, as a mutual-TLS RPC proxy does.
func startPayRPCTLS(t *testing.T, user, pass string, serverCert tls.Certificate, clientCAs *x509.CertPool) *payRPCTLS {
	t.Helper()
	s := &payRPCTLS{payRPCServer: &payRPCServer{user: user, pass: pass, digest: true, nonce: "nonce-tls", params: map[string]json.RawMessage{},
		handle: func(path, method string, params json.RawMessage) (any, int, string) {
			return map[string]any{"ok": true, "path": path}, 0, ""
		}}}
	s.Server = httptest.NewUnstartedServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.TLS == nil {
			t.Error("request reached the handler without TLS")
		} else if len(r.TLS.PeerCertificates) > 0 {
			s.peer.Store(r.TLS.PeerCertificates[0].Subject.CommonName)
		}
		s.serve(w, r)
	}))
	s.Config.ConnState = func(_ net.Conn, state http.ConnState) {
		if state == http.StateNew {
			s.conns.Add(1)
		}
	}
	s.Config.ErrorLog = log.New(io.Discard, "", 0) // the refused handshakes are expected
	s.TLS = &tls.Config{Certificates: []tls.Certificate{serverCert}, MinVersion: tls.VersionTLS12}
	if clientCAs != nil {
		s.TLS.ClientAuth, s.TLS.ClientCAs = tls.RequireAndVerifyClientCert, clientCAs
	}
	s.StartTLS()
	t.Cleanup(s.Close)
	return s
}

func (s *payRPCServer) callCount() int {
	s.mu.Lock()
	defer s.mu.Unlock()
	return len(s.calls)
}

// refusedOverTLS asserts that a client configured from the current environment fails to call rawURL and that no
// request reached the server; contains, when set, must appear in the error.
func refusedOverTLS(t *testing.T, s *payRPCTLS, rawURL, what, contains string) {
	t.Helper()
	before := s.callCount()
	c, err := newRPCClient("monero wallet", rawURL, "2.0", true)
	if err != nil {
		t.Fatalf("%s: %v", what, err)
	}
	err = c.call(context.Background(), "/json_rpc", "get_version", nil, nil)
	if err == nil || !strings.Contains(err.Error(), contains) {
		t.Fatalf("%s: %v", what, err)
	}
	if s.pass != "" && strings.Contains(err.Error(), s.pass) {
		t.Fatalf("%s: error names the password", what)
	}
	if s.callCount() != before {
		t.Fatalf("%s: a request reached the server", what)
	}
}

// A-563 (DA66-3): the production Monero wallet and daemon RPC transport is authenticated HTTPS to a private CA
// (MONERO_RPC_CA) with HTTP Digest credentials from the URL (docs/install/enable-payments.md, native production).
// Digest's 401 challenge and the authenticated retry must both travel over the verified TLS connection, and a server
// whose certificate the configured CA did not issue, or issued for another name, must be refused before any request.
func TestMoneroRPCDigestOverTLS(t *testing.T) {
	ca := newTestPKI(t, "monero-rpc-ca")
	serverCert, _, _ := ca.leaf(t, "wallet-rpc", x509.ExtKeyUsageServerAuth, net.IPv4(127, 0, 0, 1))
	s := startPayRPCTLS(t, "wallet", "digest-tls-pass", serverCert, nil)
	if !strings.HasPrefix(s.URL, "https://") {
		t.Fatalf("server is not TLS: %s", s.URL)
	}
	authURL := strings.Replace(s.URL, "https://", "https://wallet:digest-tls-pass@", 1)
	caPath := ca.caFile(t)
	setMoneroRPCTLSEnv(t, caPath, "", "")
	c, err := newRPCClient("monero wallet", authURL, "2.0", true)
	if err != nil {
		t.Fatal(err)
	}
	var out struct {
		OK   bool
		Path string
	}
	for i := 0; i < 3; i++ {
		if err := c.call(context.Background(), "/json_rpc", "get_version", nil, &out); err != nil || !out.OK || out.Path != "/json_rpc" {
			t.Fatalf("call %d over TLS: %v %+v", i, err, out)
		}
	}
	s.mu.Lock()
	challenges, nc, calls := s.challenges, s.lastNC, len(s.calls)
	s.mu.Unlock()
	// One 401 challenge answered on the same TLS connection (Monero binds the nonce to it), then reused.
	if challenges != 1 || nc != "00000003" || calls != 3 || s.conns.Load() != 1 {
		t.Fatalf("Digest over TLS: challenges=%d nc=%s calls=%d TLS connections=%d", challenges, nc, calls, s.conns.Load())
	}
	wrong, err := newRPCClient("monero wallet", strings.Replace(authURL, "digest-tls-pass", "nope", 1), "2.0", true)
	if err != nil {
		t.Fatal(err)
	}
	if err := wrong.call(context.Background(), "/json_rpc", "get_version", nil, nil); err == nil || !strings.Contains(err.Error(), "credentials rejected") {
		t.Fatalf("wrong Digest password over TLS: %v", err)
	}

	// A CA the operator did not configure: the server's certificate is not issued by MONERO_RPC_CA.
	setMoneroRPCTLSEnv(t, newTestPKI(t, "other-ca").caFile(t), "", "")
	refusedOverTLS(t, s, authURL, "server certificate not issued by MONERO_RPC_CA", "certificate")
	// No MONERO_RPC_CA: the system roots do not trust the private CA either.
	setMoneroRPCTLSEnv(t, "", "", "")
	refusedOverTLS(t, s, authURL, "private CA without MONERO_RPC_CA", "certificate")
	// The configured CA, but a certificate issued for another address: hostname verification stays on.
	misnamedCert, _, _ := ca.leaf(t, "elsewhere", x509.ExtKeyUsageServerAuth, net.IPv4(10, 9, 8, 7))
	misnamed := startPayRPCTLS(t, "wallet", "digest-tls-pass", misnamedCert, nil)
	setMoneroRPCTLSEnv(t, caPath, "", "")
	refusedOverTLS(t, misnamed, strings.Replace(misnamed.URL, "https://", "https://wallet:digest-tls-pass@", 1), "certificate for another address", "certificate")

	// The code's plaintext rule: Monero RPC TLS files with an http:// endpoint are refused when the client is built,
	// never silently ignored. Plain http without TLS files stays allowed (local and fakechain nodes); the code has no
	// separate rule for remote hosts.
	if _, err := newRPCClient("monero wallet", strings.Replace(authURL, "https://", "http://", 1), "2.0", true); err == nil || !strings.Contains(err.Error(), "HTTPS") {
		t.Fatalf("TLS files with an http endpoint: %v", err)
	}
}

// A-563 (DA66-3): with the supported mutual-TLS client identity (MONERO_RPC_CERT and MONERO_RPC_KEY, imported by
// --monero-rpc-cert/--monero-rpc-key), a proxy that requires and verifies a client certificate accepts the configured
// one, and refuses the client without it or with a certificate its client CA did not issue.
func TestMoneroRPCMutualTLSAccepted(t *testing.T) {
	ca := newTestPKI(t, "monero-rpc-ca")
	clientCA := newTestPKI(t, "monero-rpc-client-ca")
	serverCert, _, _ := ca.leaf(t, "wallet-proxy", x509.ExtKeyUsageServerAuth, net.IPv4(127, 0, 0, 1))
	_, certPath, keyPath := clientCA.leaf(t, "market-app", x509.ExtKeyUsageClientAuth)
	s := startPayRPCTLS(t, "", "", serverCert, clientCA.pool())
	caPath := ca.caFile(t)

	setMoneroRPCTLSEnv(t, caPath, certPath, keyPath)
	c, err := newRPCClient("monero wallet", s.URL, "2.0", true)
	if err != nil {
		t.Fatal(err)
	}
	var out struct{ OK bool }
	if err := c.call(context.Background(), "/json_rpc", "get_version", nil, &out); err != nil || !out.OK {
		t.Fatalf("configured client certificate refused: %v %+v", err, out)
	}
	if got, _ := s.peer.Load().(string); got != "market-app" {
		t.Fatalf("server saw client certificate %q", got)
	}

	setMoneroRPCTLSEnv(t, caPath, "", "")
	refusedOverTLS(t, s, s.URL, "no client certificate", "")
	_, rogueCert, rogueKey := newTestPKI(t, "rogue-client-ca").leaf(t, "market-app", x509.ExtKeyUsageClientAuth)
	setMoneroRPCTLSEnv(t, caPath, rogueCert, rogueKey)
	refusedOverTLS(t, s, s.URL, "client certificate from another CA", "")
	// A client certificate from the server's CA does not satisfy a proxy that trusts only its client CA.
	_, sameCACert, sameCAKey := ca.leaf(t, "server-ca-client", x509.ExtKeyUsageClientAuth)
	setMoneroRPCTLSEnv(t, caPath, sameCACert, sameCAKey)
	refusedOverTLS(t, s, s.URL, "client certificate from the server CA", "")
}
